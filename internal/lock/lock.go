// Package lock writes and compares .csaw/lock.yml, a per-project record of
// exactly what csaw mounted: each source's resolved commit and each mounted
// file's content hash. Commit it to reproduce a mount with `csaw use
// --frozen` and to let `csaw audit` prove the mounted context matches.
package lock

import (
	"context"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"

	"gopkg.in/yaml.v3"

	"github.com/NicholasCullenCooper/csaw/internal/git"
	"github.com/NicholasCullenCooper/csaw/internal/pinning"
	"github.com/NicholasCullenCooper/csaw/internal/runtime"
	"github.com/NicholasCullenCooper/csaw/internal/sources"
	"github.com/NicholasCullenCooper/csaw/internal/workspace"
)

const (
	DirName  = ".csaw"
	FileName = "lock.yml"
	Version  = 1
)

type File struct {
	Version     int          `yaml:"version"`
	GeneratedAt string       `yaml:"generated_at,omitempty"`
	Sources     []SourceLock `yaml:"sources"`
	Entries     []EntryLock  `yaml:"entries"`
}

type SourceLock struct {
	Name         string `yaml:"name"`
	Kind         string `yaml:"kind"`
	URL          string `yaml:"url,omitempty"`
	RefRequested string `yaml:"ref_requested,omitempty"`
	RefResolved  string `yaml:"ref_resolved,omitempty"`
}

type EntryLock struct {
	Path          string `yaml:"path"`
	Source        string `yaml:"source"`
	SourcePath    string `yaml:"source_path,omitempty"`
	Mode          string `yaml:"mode,omitempty"`
	ContentSHA256 string `yaml:"content_sha256,omitempty"`
}

// SourceInfo is what the lock records about one configured source.
type SourceInfo struct {
	Root         string
	Kind         string
	URL          string
	RefRequested string
	RefResolved  string
}

func Path(projectRoot string) string {
	return filepath.Join(projectRoot, DirName, FileName)
}

// Read loads the project lock. found is false when there is none.
func Read(projectRoot string) (File, bool, error) {
	content, err := os.ReadFile(Path(projectRoot))
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return File{}, false, nil
		}
		return File{}, false, err
	}
	var file File
	if err := yaml.Unmarshal([]byte(runtime.StripBOM(string(content))), &file); err != nil {
		return File{}, false, fmt.Errorf("parse %s: %w", Path(projectRoot), err)
	}
	if file.Version != Version {
		return File{}, false, fmt.Errorf("%s: unsupported lock version %d (want %d)", Path(projectRoot), file.Version, Version)
	}
	return file, true, nil
}

// Write stores the lock at .csaw/lock.yml.
func Write(projectRoot string, file File) error {
	if err := os.MkdirAll(filepath.Dir(Path(projectRoot)), 0o755); err != nil {
		return err
	}
	file.Version = Version
	if file.GeneratedAt == "" {
		file.GeneratedAt = time.Now().UTC().Format(time.RFC3339)
	}
	content, err := yaml.Marshal(file)
	if err != nil {
		return err
	}
	header := "# csaw lock: what is mounted in this project. Regenerated by csaw use, mount, and update.\n# Commit it to reproduce the mount with `csaw use --frozen` and to let `csaw audit` verify it.\n"
	return os.WriteFile(Path(projectRoot), append([]byte(header), content...), 0o644)
}

// Remove deletes the lock file if present.
func Remove(projectRoot string) error {
	if err := os.Remove(Path(projectRoot)); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	return nil
}

// SourceInfos describes every configured source as the lock records it:
// checkout root (the pinned worktree when the project pins it), requested
// ref, and the commit currently checked out.
func SourceInfos(ctx context.Context, g git.Git, paths runtime.Paths, projectRoot string) (map[string]SourceInfo, error) {
	manager := sources.Manager{Paths: paths, Git: g}
	cfg, err := manager.Load()
	if err != nil {
		return nil, err
	}
	catalog, err := manager.ExistingCatalog()
	if err != nil {
		return nil, err
	}
	roots := make(map[string]string, len(catalog))
	for _, entry := range catalog {
		roots[entry.Name] = entry.Root
	}
	pinState, _ := pinning.Read(projectRoot)

	infos := make(map[string]SourceInfo, len(cfg.Sources))
	for _, source := range cfg.Sources {
		info := SourceInfo{Kind: source.Kind, URL: source.URL, RefRequested: source.Ref, Root: roots[source.Name]}
		if source.Kind == sources.KindLocal {
			info.URL = source.Path
		}
		if ref, ok := pinning.Get(pinState, source.Name); ok && source.Kind == sources.KindRemote {
			info.RefRequested = ref
			worktree := manager.WorktreePath(source, projectRoot)
			if _, err := os.Stat(worktree); err == nil {
				info.Root = worktree
			}
		}
		if info.Root != "" {
			if sha, err := g.Run(ctx, info.Root, "rev-parse", "HEAD"); err == nil {
				info.RefResolved = strings.TrimSpace(sha)
			}
		}
		infos[source.Name] = info
	}
	return infos, nil
}

// FromState builds the lock for a mount state. Symlink-mode entries carry no
// content hash in state, so the source file is hashed now.
func FromState(state workspace.MountState, infos map[string]SourceInfo) (File, error) {
	file := File{Version: Version}

	used := make(map[string]bool)
	for _, entry := range state.Entries {
		used[entry.SourceName] = true
	}
	for name := range used {
		info := infos[name]
		file.Sources = append(file.Sources, SourceLock{
			Name:         name,
			Kind:         info.Kind,
			URL:          info.URL,
			RefRequested: info.RefRequested,
			RefResolved:  info.RefResolved,
		})
	}
	sort.Slice(file.Sources, func(i, j int) bool { return file.Sources[i].Name < file.Sources[j].Name })

	for _, entry := range state.Entries {
		locked := EntryLock{
			Path:          entry.RelativePath,
			Source:        entry.SourceName,
			Mode:          entry.Mode,
			ContentSHA256: entry.ContentSHA256,
		}
		if entry.Generated {
			locked.Mode = "generated"
		}
		if locked.Mode == "" {
			locked.Mode = "symlink"
		}
		if locked.ContentSHA256 == "" {
			hash, err := workspace.FileSHA256(entry.SourcePath)
			if err != nil {
				return File{}, fmt.Errorf("hash %s: %w", entry.SourcePath, err)
			}
			locked.ContentSHA256 = hash
		}
		if root := infos[entry.SourceName].Root; root != "" {
			if rel, err := filepath.Rel(root, entry.SourcePath); err == nil && !strings.HasPrefix(rel, "..") {
				locked.SourcePath = filepath.ToSlash(rel)
			}
		}
		file.Entries = append(file.Entries, locked)
	}
	sort.Slice(file.Entries, func(i, j int) bool { return file.Entries[i].Path < file.Entries[j].Path })

	return file, nil
}

// Diff lists every way want differs from have, ignoring GeneratedAt. An
// empty result means the two describe the same mount.
func Diff(want File, have File) []string {
	var diffs []string

	wantSources := indexSources(want.Sources)
	haveSources := indexSources(have.Sources)
	for _, name := range sortedSourceNames(wantSources, haveSources) {
		w, inWant := wantSources[name]
		h, inHave := haveSources[name]
		switch {
		case !inHave:
			diffs = append(diffs, fmt.Sprintf("source %s: locked but not mounted", name))
		case !inWant:
			diffs = append(diffs, fmt.Sprintf("source %s: mounted but not locked", name))
		default:
			if w.URL != h.URL {
				diffs = append(diffs, fmt.Sprintf("source %s: url %s, locked %s", name, h.URL, w.URL))
			}
			if w.RefRequested != h.RefRequested {
				diffs = append(diffs, fmt.Sprintf("source %s: ref %s, locked %s", name, orNone(h.RefRequested), orNone(w.RefRequested)))
			}
			if w.RefResolved != "" && h.RefResolved != "" && w.RefResolved != h.RefResolved {
				diffs = append(diffs, fmt.Sprintf("source %s: commit %s, locked %s", name, short(h.RefResolved), short(w.RefResolved)))
			}
		}
	}

	wantEntries := indexEntries(want.Entries)
	haveEntries := indexEntries(have.Entries)
	for _, path := range sortedEntryPaths(wantEntries, haveEntries) {
		w, inWant := wantEntries[path]
		h, inHave := haveEntries[path]
		switch {
		case !inHave:
			diffs = append(diffs, fmt.Sprintf("%s: locked but not mounted", path))
		case !inWant:
			diffs = append(diffs, fmt.Sprintf("%s: mounted but not locked", path))
		default:
			if w.Source != h.Source {
				diffs = append(diffs, fmt.Sprintf("%s: from %s, locked %s", path, h.Source, w.Source))
			}
			if w.Mode != h.Mode {
				diffs = append(diffs, fmt.Sprintf("%s: mode %s, locked %s", path, h.Mode, w.Mode))
			}
			if w.ContentSHA256 != h.ContentSHA256 {
				diffs = append(diffs, fmt.Sprintf("%s: content %s, locked %s", path, short(h.ContentSHA256), short(w.ContentSHA256)))
			}
		}
	}

	return diffs
}

func indexSources(items []SourceLock) map[string]SourceLock {
	out := make(map[string]SourceLock, len(items))
	for _, item := range items {
		out[item.Name] = item
	}
	return out
}

func indexEntries(items []EntryLock) map[string]EntryLock {
	out := make(map[string]EntryLock, len(items))
	for _, item := range items {
		out[item.Path] = item
	}
	return out
}

func sortedSourceNames(a, b map[string]SourceLock) []string {
	seen := make(map[string]bool)
	for name := range a {
		seen[name] = true
	}
	for name := range b {
		seen[name] = true
	}
	return sortedKeys(seen)
}

func sortedEntryPaths(a, b map[string]EntryLock) []string {
	seen := make(map[string]bool)
	for path := range a {
		seen[path] = true
	}
	for path := range b {
		seen[path] = true
	}
	return sortedKeys(seen)
}

func sortedKeys(set map[string]bool) []string {
	keys := make([]string, 0, len(set))
	for key := range set {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

func short(hash string) string {
	if len(hash) > 12 {
		return hash[:12]
	}
	if hash == "" {
		return "(none)"
	}
	return hash
}

func orNone(value string) string {
	if value == "" {
		return "(default branch)"
	}
	return value
}
